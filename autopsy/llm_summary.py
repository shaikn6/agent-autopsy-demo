"""Optional LLM root-cause layer.

The deterministic detectors in :mod:`autopsy.patterns` remain the source of truth. This module only *explains* the
patterns they already found, in plain language. It never runs a detector and never hard-fails: if no model is reachable
(no ``HF_TOKEN``, the model is unavailable, the account is out of credits, or the call times out) it degrades to a
templated summary built from the same patterns. No paid key and no torch/transformers download is required.

Input is the report dict (``AutopsyReport.to_json`` parsed), so the caller can pass the raw report JSON straight in.
"""

from __future__ import annotations

import os
from typing import Any

_DEFAULT_MODEL = "meta-llama/Llama-3.1-8B-Instruct"  # served on HF Inference; override with AUTOPSY_LLM_MODEL
_SEVERITY_ORDER = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}


def _ordered(patterns: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return sorted(patterns, key=lambda p: _SEVERITY_ORDER.get(p.get("severity", ""), 9))


def _trace_digest(report: dict[str, Any], limit: int = 14) -> str:
    lines: list[str] = []
    for node in report.get("graph", {}).get("nodes", [])[:limit]:
        md = node.get("metadata", {}) or {}
        detail = (
            md.get("tool_name")
            or md.get("prompt")
            or md.get("description")
            or md.get("error_message")
            or ""
        )
        lines.append(f"{node.get('id')} {node.get('type')}: {str(detail)[:150]}")
    return "\n".join(lines)


def templated_summary(report: dict[str, Any], reason: str | None = None) -> str:
    """Deterministic fallback: a severity-ordered plain-language recap of the detected patterns."""
    patterns = report.get("failure_patterns", [])
    if not patterns:
        return "No failure patterns were detected, so there is nothing to explain."
    out: list[str] = []
    for p in _ordered(patterns):
        ids = ", ".join(p.get("step_ids", [])) or "—"
        out.append(
            f"- **[{p.get('severity')}] {p.get('name')}** (steps {ids}): {p.get('description')} "
            f"_Fix:_ {p.get('recommendation')}"
        )
    header = "Templated root-cause summary"
    header += f" (no model reachable: {reason})" if reason else ""
    return header + ":\n\n" + "\n".join(out)


def _build_messages(report: dict[str, Any]) -> list[dict[str, str]]:
    plist = "\n".join(
        f"- {p.get('name')} [{p.get('severity')}] steps {p.get('step_ids')}: {p.get('description')} "
        f"(suggested fix: {p.get('recommendation')})"
        for p in _ordered(report.get("failure_patterns", []))
    )
    user = (
        f"An automated analyzer inspected an LLM agent run named '{report.get('agent_name')}' "
        f"({report.get('total_steps')} steps, {report.get('total_tokens')} tokens, status {report.get('status')}).\n\n"
        f"Deterministic detectors found these failure patterns (authoritative — do not invent others):\n{plist}\n\n"
        f"Trace steps:\n{_trace_digest(report)}\n\n"
        "In 4-6 sentences, explain the single most likely root cause that ties these findings together, and the one "
        "most important fix. Refer only to the findings above; do not invent new problems or step ids."
    )
    return [
        {
            "role": "system",
            "content": "You are a precise SRE assistant explaining why an LLM agent run failed. Be concise and concrete.",
        },
        {"role": "user", "content": user},
    ]


def generate_root_cause(report: dict[str, Any]) -> tuple[str, str]:
    """Explain the detected patterns. Returns ``(text, source_label)`` and never raises.

    ``source_label`` is one of ``"deterministic"`` (nothing to explain), ``"templated"`` (fallback) or
    ``"generated by <model>"`` (an LLM produced the text).
    """
    patterns = report.get("failure_patterns", [])
    if not patterns:
        return (
            "No failure patterns were detected — the deterministic analysis found nothing to explain.",
            "deterministic",
        )

    token = os.getenv("HF_TOKEN") or os.getenv("HUGGING_FACE_HUB_TOKEN")
    if not token:
        return (templated_summary(report, reason="HF_TOKEN not set"), "templated")

    model = os.getenv("AUTOPSY_LLM_MODEL", _DEFAULT_MODEL)
    try:
        from huggingface_hub import InferenceClient

        client = InferenceClient(model=model, token=token, timeout=20)
        resp = client.chat_completion(
            messages=_build_messages(report), max_tokens=400, temperature=0.3
        )
        text = (resp.choices[0].message.content or "").strip()
        if not text:
            return (templated_summary(report, reason="model returned empty text"), "templated")
        return (text, f"generated by {model}")
    except Exception as exc:  # noqa: BLE001 — any failure degrades to the template, never crashes the app
        return (templated_summary(report, reason=type(exc).__name__), "templated")
